"""Lay out the score-line dots (copied from ep01's kit; same output) from the series data.

Reads ../../_data/scores.npz (seed 13, model a) and writes dots.js, which
sets window.SCORE_DOTS: every request's home position on the score line,
its score, and its confusion-matrix group (tp / fp / fn / tn at the ledger
threshold 0.70) with its rank inside that group, so a beat can fly it to
a slot in the box.

Users pile up above the axis (a dot plot: one column per COL_W px of
score, stacked upward, the tall pile soft-capped at PILE_H); attacks pile
down below it in bigger dots.

Run from this folder:  ../../../../.venv/bin/python make_dots.py
"""
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
T_A = 0.70                      # ledger: model_a_box.t
X0, X1 = 120.0, 920.0           # score 0 and 1, px (must match score.js)
AXIS_Y = 590.0
PILE_H = 190.0                  # user pile height above the axis, px
COL_W = 4.0                     # user column width, px
DOT_PITCH = 3.4                 # user stacking pitch in the tail, px
ATK_COL_W, ATK_PITCH = 14.0, 13.0


def sx(s):
    return X0 + s * (X1 - X0)


def users_layout(s):
    cols = np.floor(sx(s) / COL_W).astype(int)
    order = np.argsort(s, kind="stable")
    k = np.zeros_like(cols)
    seen = {}
    for i in order:
        c = cols[i]; k[i] = seen.get(c, 0); seen[c] = k[i] + 1
    # soft cap: true DOT_PITCH stacking in the tail, compressed in the tall
    # pile, so 1-2 dots in a tail column still read as dots
    x = cols * COL_W + COL_W / 2
    y = AXIS_Y - 3 - PILE_H * (1 - np.exp(-k * DOT_PITCH / PILE_H))
    return x, y, DOT_PITCH


def attacks_layout(s):
    cols = np.floor(sx(s) / ATK_COL_W).astype(int)
    order = np.argsort(s, kind="stable")
    k = np.zeros_like(cols); seen = {}
    for i in order:
        c = cols[i]; k[i] = seen.get(c, 0); seen[c] = k[i] + 1
    x = cols * ATK_COL_W + ATK_COL_W / 2
    y = AXIS_Y + 12 + k * ATK_PITCH
    return x, y


def main():
    d = np.load(HERE.parents[1] / "_data" / "scores.npz")
    y, a = d["y"], d["a"]
    att, usr = a[y == 1], a[y == 0]
    ux, uy, pitch = users_layout(usr)
    ax, ay = attacks_layout(att)

    def group(s, hit, miss):
        g = np.where(s > T_A, hit, miss)
        rank = np.zeros(len(s), int)
        for name in (hit, miss):
            idx = np.where(g == name)[0]
            rank[idx[np.argsort(-s[idx], kind="stable")]] = np.arange(len(idx))
        return g, rank

    ug, ur = group(usr, "fp", "tn")
    ag, ar = group(att, "tp", "fn")
    counts = {k: int(v) for k, v in zip(*np.unique(np.concatenate([ug, ag]), return_counts=True))}
    assert counts == {"tp": 40, "fp": 60, "fn": 10, "tn": 9890}, counts

    r1 = lambda v: [round(float(t), 1) for t in v]
    out = {
        "threshold": T_A, "x0": X0, "x1": X1, "axisY": AXIS_Y, "userPitch": round(pitch, 3),
        "counts": counts,
        "users": {"x": r1(ux), "y": r1(uy), "s": [round(float(t), 4) for t in usr],
                  "g": [str(t) for t in ug], "r": [int(t) for t in ur]},
        "attacks": {"x": r1(ax), "y": r1(ay), "s": [round(float(t), 4) for t in att],
                    "g": [str(t) for t in ag], "r": [int(t) for t in ar]},
    }
    js = "// generated by make_dots.py from _data/scores.npz (seed 13); do not edit\n"
    js += "window.SCORE_DOTS = " + json.dumps(out, separators=(",", ":")) + ";\n"
    (HERE / "dots.js").write_text(js)
    print(counts, "user pitch", round(pitch, 2), "px; attack rows", int((ay.max() - AXIS_Y - 12) / ATK_PITCH) + 1,
          "; dots.js", len(js) // 1024, "KB")


if __name__ == "__main__":
    main()
