"""Lay out ep04's score line and curves from the series data.

Reads ../../_data/scores.npz (seed 13, model a) and writes dots.js, which
sets window.SCORE_DOTS: every request's home position on the score line
and its score (a beat flags a dot by comparing its score with the
threshold), plus the curve: one point per cut of the ranked list, each
carrying its ROC position (fpr, tpr) and its PR position (recall,
precision), so the ROC -> PR morph moves the same points. Also the AP
steps (one per attack), which sum to the ledger's PR-AUC.

The score line is ep01's (make_dots.py there), shorter: the plot sits
under it.

Run from this folder:  ../../../../.venv/bin/python make_dots.py
"""
import json
from pathlib import Path

import numpy as np
from sklearn.metrics import average_precision_score, roc_auc_score

HERE = Path(__file__).resolve().parent
X0, X1 = 120.0, 920.0           # score 0 and 1, px (must match score.js)
AXIS_Y = 530.0
PILE_H = 122.0                  # user pile height above the axis, px
COL_W = 4.0
DOT_PITCH = 3.4
ATK_COL_W, ATK_PITCH = 14.0, 13.0


def sx(s):
    return X0 + s * (X1 - X0)


def pile(s, col_w):
    cols = np.floor(sx(s) / col_w).astype(int)
    k = np.zeros_like(cols); seen = {}
    for i in np.argsort(s, kind="stable"):
        c = cols[i]; k[i] = seen.get(c, 0); seen[c] = k[i] + 1
    return cols * col_w + col_w / 2, k


def curve(y, s):
    """Points at cuts k of the ranked list (k = number flagged)."""
    o = np.argsort(-s, kind="stable"); ys = y[o]
    tp = np.concatenate([[0], np.cumsum(ys)]); fp = np.concatenate([[0], np.cumsum(1 - ys)])
    P, N = int(ys.sum()), int((1 - ys).sum())
    att = np.where(ys == 1)[0] + 1                       # k right after each attack
    ks = set(att) | set(att - 1) | set(range(0, 2000, 8)) | set(range(2000, len(ys) + 1, 100)) | {len(ys)}
    ks = sorted(k for k in ks if 0 <= k <= len(ys))
    pts = []
    for k in ks:
        prec = 1.0 if k == 0 else tp[k] / k
        pts.append([round(fp[k] / N, 5), round(tp[k] / P, 4), round(float(prec), 4)])
    steps = [round(float(tp[k] / k), 4) for k in att]      # precision at each attack: AP = mean
    return pts, steps


def main():
    d = np.load(HERE.parents[1] / "_data" / "scores.npz")
    y, a = d["y"], d["a"]
    att, usr = a[y == 1], a[y == 0]
    ux, uk = pile(usr, COL_W)
    uy = AXIS_Y - 3 - PILE_H * (1 - np.exp(-uk * DOT_PITCH / PILE_H))
    ax, ak = pile(att, ATK_COL_W)
    ay = AXIS_Y + 12 + ak * ATK_PITCH
    pts, steps = curve(y, a)

    ap = float(np.mean(steps))
    assert round(ap, 3) == round(average_precision_score(y, a), 3) == 0.556, ap
    assert round(roc_auc_score(y, a), 3) == 0.985
    for t, tp, fp in ((0.70, 40, 60), (0.55, 44, 233)):
        assert ((att > t).sum(), (usr > t).sum()) == (tp, fp), t

    r1 = lambda v: [round(float(t), 1) for t in v]
    out = {
        "x0": X0, "x1": X1, "axisY": AXIS_Y,
        "users": {"x": r1(ux), "y": r1(uy), "s": [round(float(t), 4) for t in usr]},
        "attacks": {"x": r1(ax), "y": r1(ay), "s": [round(float(t), 4) for t in att]},
        "curve": pts, "apSteps": steps,
    }
    js = "// generated by make_dots.py from _data/scores.npz (seed 13); do not edit\n"
    js += "window.SCORE_DOTS = " + json.dumps(out, separators=(",", ":")) + ";\n"
    (HERE / "dots.js").write_text(js)
    print("curve points", len(pts), "AP", round(ap, 4), "attack rows", int(ak.max()) + 1,
          "user pile top", round(float(uy.min()), 1), "; dots.js", len(js) // 1024, "KB")


if __name__ == "__main__":
    main()
