"""Group the voiceover's words into short captions: out/words.json -> footage/captions.js.

Run after make_audio.sh and tools/word_times.py (see concept.md, "Sound").
A caption is up to 3 words or 20 characters and never crosses a sentence or a
comma; it shows from its first word until the next caption, or until 0.35 s
after its line's last word.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
words = json.loads((HERE / "out" / "words.json").read_text())

# word_times.py splits each line by syllables; in the drowning line it missed the
# pause after "drowned" (RMS envelope: "drowned" ends 1.07 s into the line, "So" starts at 1.37),
# so that line's words are timed by hand from the envelope.
# Offsets from the line's start (its first word's placed time).
DROWN = [0.02, 0.17, 0.31, 0.53, 1.37, 1.49, 1.63, 1.80, 1.90, 2.20, 2.30, 2.37]
line = [w for w in words if w["seg"] == 2]
base = line[0]["t"]
assert [w["word"] for w in line][3] == "drowned." and len(line) == len(DROWN), [w["word"] for w in line]
for w, t in zip(line, DROWN):
    w["t"] = round(base + t, 3)
line[3]["end"], line[-1]["end"] = round(base + 1.07, 3), round(base + 2.65, 3)
words.sort(key=lambda w: w["t"])

caps, cur = [], []
def flush():
    if cur:
        caps.append({"t0": cur[0]["t"], "text": " ".join(x["word"] for x in cur), "seg": cur[0]["seg"],
                     "last": cur[-1].get("end", cur[-1]["t"] + 0.3)})
for w in words:
    if cur and (w["seg"] != cur[0]["seg"] or len(cur) >= 3 or len(" ".join(x["word"] for x in cur + [w])) > 20):
        flush(); cur = []
    cur.append(w)
    if re.search(r"[.,?!]$", w["word"]):
        flush(); cur = []
flush()
for i, cap in enumerate(caps):
    nxt = caps[i + 1] if i + 1 < len(caps) else None
    cap["t1"] = round(nxt["t0"] if nxt and nxt["seg"] == cap["seg"] else cap["last"] + 0.35, 3)
    cap["t0"] = round(cap["t0"], 3)
out = [{"t0": c["t0"], "t1": c["t1"], "text": c["text"]} for c in caps]
(HERE / "footage" / "captions.js").write_text(
    "// Generated by make_captions.py from out/words.json: voiceover captions in video seconds.\n"
    f"window.CAPTIONS = {json.dumps(out, indent=0)};\n")
for c in out:
    print(f"{c['t0']:6.2f}-{c['t1']:6.2f}  {c['text']}")
