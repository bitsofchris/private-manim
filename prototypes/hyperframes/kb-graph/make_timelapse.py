"""Build footage/timelapse.mp4 and footage/edit.js from edit.json.

Each segment plays part of one select (already cropped to the game window)
sped up to fill its `seconds`, centre-cropped to a square. A segment may start
inside its select: the select's own start comes from its file name (..._HHMMSS.mp4). The tail holds the last frame.
edit.js gives the composition the same clock -> video time map, so the cards
land on the footage they describe. Run: python3 make_timelapse.py
"""
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
edit = json.loads((HERE / "edit.json").read_text())
src, fps, size = Path(edit["source"]), edit["fps"], edit["size"]


def secs(clock):
    h, m, s = (int(x) for x in clock.split(":"))
    return h * 3600 + m * 60 + s


inputs, chains, points, t = [], [], [], 0.0
for i, seg in enumerate(edit["segments"]):
    path = next(src.glob(f"{seg['select']}_*.mp4"))
    length = secs(seg["out"]) - secs(seg["in"])
    stem = path.stem.rsplit("_", 1)[1]
    skip = secs(seg["in"]) - secs(f"{stem[:2]}:{stem[2:4]}:{stem[4:]}")
    speed = length / seg["seconds"]
    inputs += ["-i", str(path)]
    chains.append(
        f"[{i}:v]trim={skip}:{skip + length},setpts=(PTS-STARTPTS)/{speed:.4f},fps={fps},"
        f"crop=ih:ih,scale={size}:{size},setsar=1,tpad=stop_mode=clone:stop_duration=1,trim=0:{seg['seconds']},setpts=PTS-STARTPTS[v{i}]"
    )
    points.append([seg["in"], t])
    t += seg["seconds"]
    points.append([seg["out"], t])
tail = edit["tail"]
points.append([tail["clock"], t + tail["seconds"]])
total = t + tail["seconds"]

n = len(edit["segments"])
graph = ";".join(chains) + ";" + "".join(f"[v{i}]" for i in range(n))
graph += f"concat=n={n}:v=1:a=0,tpad=stop_mode=clone:stop_duration={tail['seconds']}[out]"
out = HERE / "footage" / "timelapse.mp4"
out.parent.mkdir(exist_ok=True)
subprocess.run(
    ["ffmpeg", "-v", "error", "-y", *inputs, "-filter_complex", graph, "-map", "[out]",
     "-c:v", "libx264", "-preset", "fast", "-crf", "18", "-pix_fmt", "yuv420p", "-an", str(out)],
    check=True,
)
(HERE / "footage" / "edit.js").write_text(
    "// Generated by make_timelapse.py from edit.json: clock -> video seconds.\n"
    f"window.EDIT = {json.dumps({'map': points, 'seconds': total})};\n"
)
print(f"{out} ({total:g} s), {len(points)} map points")
