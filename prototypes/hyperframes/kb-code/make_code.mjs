// Export the code AgentMiner wrote during the diamond run to footage/code.js.
//   node make_code.mjs [kb]      (kb defaults to ~/augi-fresh-kb, the run's knowledge base)
// Each note is read as it was in the commit that created it, so the code view types what the
// agent saved at that moment. Helpers keep their `## Code` block, wrapped in the signature from
// `implementation:`; lessons keep their `## Procedure`, as comments to type above the helper they name.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { homedir } from "node:os";

const KB = process.argv[2] || `${homedir()}/augi-fresh-kb`;
const HELPERS = ["chop-logs", "craft-item", "mine-blocks", "ensure-table", "smelt-items",
                 "descend-scan-ore", "staircase-down", "give-item-to-player"];
const LESSONS = ["craft-one-at-a-time", "check-movement-progress"];
const WRAP = 44;                                       // comment width, so typed lessons fit the band

const git = (...a) => execFileSync("git", ["-C", KB, ...a], { encoding: "utf8" });
const firstVersion = id => {
  const glob = `learned/*/${id}.md`;
  const sha = git("log", "--diff-filter=A", "--format=%h", "--", glob).trim().split("\n").pop();
  const path = git("show", "--name-only", "--format=", sha, "--", glob).trim();
  return git("show", `${sha}:${path}`);
};
const section = (md, re) => (md.match(re) || [, ""])[1].replace(/\s+$/, "").split("\n");
const wrap = text => {
  const out = []; let line = "";
  for (const w of text.split(/\s+/)) {
    if (line && line.length + 1 + w.length > WRAP) { out.push(line); line = w; } else line = line ? `${line} ${w}` : w;
  }
  return line ? out.concat(line) : out;
};

const code = {};
for (const id of HELPERS) {
  const md = firstVersion(id);
  // implementation: "helper program: helpers.chopLogs({ count = 6, maxDistance = 32 })"; the body reads `args`
  const [, fn, inner] = md.match(/helpers\.(\w+)\((.*)\)"/);
  const params = inner.includes("(none)") ? [] : inner.replace(/^\{\s*|\s*\}$/g, "").split(/,(?![^[]*\])/)
    .map(p => p.trim().split(/[\s=:]/)[0]);
  const body = section(md, /```js\n([\s\S]*?)```/).map(l => "  " + l);
  code[id] = { kind: "helper", fn, params, lines: [`async function ${fn}(args) {`, ...body, "}"] };
}
for (const id of LESSONS) {
  const steps = section(firstVersion(id), /## Procedure\n+([\s\S]*)$/).filter(l => l.trim());
  const lines = [`// LESSON ${id}`];
  steps.forEach(s => wrap(s).forEach((w, i) => lines.push(`// ${i ? "   " : ""}${w}`)));
  code[id] = { kind: "lesson", lines };
}
writeFileSync("footage/code.js", `// Generated by make_code.mjs from ${KB}: the code AgentMiner wrote, as first saved.\nwindow.CODE = ${JSON.stringify(code, null, 1)};\n`);
for (const id in code) console.log(id.padEnd(24), code[id].lines.length, "lines");
